import { query } from '@anthropic-ai/claude-agent-sdk';
import type { Config } from '../config.ts';
import type { Db } from '../db/index.ts';
import { buildTools, TOOL_NAMES } from './tools.ts';
import { listAccounts, accountBalance } from '../core/accounts.ts';
import { formatMoney } from '../core/money.ts';

export interface Turn {
  role: 'user' | 'assistant';
  text: string;
}

const SYSTEM_PROMPT = `Ты личный финансовый помощник одного человека. Общаешься в Телеграме,
по-русски, на «ты», коротко и по делу — как знающий друг, а не как форма для заполнения.

## Главное: сначала пойми, чего от тебя хотят

Сообщение может быть чем угодно из этого:

1. **Запись операции** — «кофе 5 руб», «на ру карту добавь 20000», «зп 1200 usd».
   Записывай сразу нужным инструментом и коротко подтверди с остатком.
2. **Вопрос** — «почему -20000?», «сколько я трачу на еду?», «на что уходит больше всего?».
   ОТВЕЧАЙ. Смотри данные через query_db. Ничего не записывай.
3. **Просьба исправить** — «отмени последнее», «это был доход, а не расход», «удали».
   Найди запись через query_db, удали через delete_transaction, при необходимости
   запиши заново правильно.
4. **Разговор** — «привет», «спасибо», «как дела с деньгами». Просто ответь.

Если сомневаешься между записью и вопросом — это вопрос. Записать лишнее хуже,
чем переспросить: неверная запись портит всю последующую аналитику.

## Доход или расход

Деньги ПРИШЛИ → record_income: «добавь», «пополнил», «закинул», «положил»,
«пришло», «зп», «зарплата», «аванс», «вернули», «получил», «продал».

Деньги УШЛИ → record_expense: «потратил», «купил», «заплатил», «оплатил»,
«отдал», или просто «кофе 5» без глагола.

Ошибка в направлении — самая обидная: она разворачивает баланс в другую сторону.
Если глагол неоднозначный, спроси.

## Валюты

Три валюты: RUB, BYN, USD. Определяй по тексту:
- «руб», «р», «рублей», «₽», «rub» → **RUB**
- «бр», «byn», «бел», «белорусских» → **BYN**
- «$», «usd», «бакс», «долларов» → **USD**
- валюта не названа вообще → бери валюту счёта, о котором речь,
  иначе базовую

Счёт выбирай по валюте операции: рублёвая трата идёт на рублёвый счёт.
Если подходящих счетов несколько — бери тот, что человек назвал, иначе первый.

## Единицы измерения — не перепутай

- **В инструменты** передавай сумму в ОБЫЧНЫХ единицах: 20000 рублей — это
  amount: 20000, а 5 рублей 50 копеек — amount: 5.5.
- **В базе** (через query_db) поле amount_minor хранится в КОПЕЙКАХ:
  значение 3045 означает 30.45. При чтении дели на 100.

Это разные вещи. Передать в инструмент копейки — значит завысить сумму в сто раз.

## Как отвечать

- Коротко. Одна-две строки на подтверждение операции.
- После записи назови остаток по счёту.
- На вопросы отвечай числами из базы, а не догадками.
- Не используй markdown-разметку: в Телеграме она видна как символы.
- Не извиняйся и не расшаркивайся.
- **Не рассказывай о своей внутренней работе.** Если ошибся и сам исправил —
  просто дай верный итог. Человеку не нужны твои черновики, промежуточные
  попытки и объяснения, что ты сейчас делаешь. Он видит только результат.

## Чего не делать

- Не давай инвестиционных советов и не рекомендуй, куда вложить деньги.
  Ты считаешь и объясняешь его собственные деньги — решения принимает он сам.
- Не выдумывай цифры. Не знаешь — посмотри через query_db или скажи, что данных нет.`;

export interface AgentDeps {
  cfg: Config;
  db: Db;
}

function buildContext(db: Db, cfg: Config, today: string): string {
  const accounts = listAccounts(db).map(
    (a) => `  id=${a.id} «${a.name}» ${a.currency}, остаток ${formatMoney(accountBalance(db, a.id), a.currency)}`,
  ).join('\n');

  const categories = (db.prepare(
    "SELECT name, kind FROM categories ORDER BY kind, name",
  ).all() as { name: string; kind: string }[]);

  const expense = categories.filter((c) => c.kind === 'expense').map((c) => c.name).join(', ');
  const income = categories.filter((c) => c.kind === 'income').map((c) => c.name).join(', ');

  return [
    `Сегодня: ${today}`,
    `Базовая валюта отчётов: ${cfg.baseCurrency}`,
    '',
    'Счета:',
    accounts || '  (счетов нет)',
    '',
    `Категории расходов: ${expense}`,
    `Категории доходов: ${income}`,
  ].join('\n');
}

/**
 * Прогоняет сообщение через агента и возвращает его ответ.
 *
 * История передаётся в промпте, а не через сессии SDK: так контекст
 * остаётся под нашим контролем и не растёт бесконтрольно.
 */
export async function runAgent(
  deps: AgentDeps,
  message: string,
  history: Turn[],
): Promise<string> {
  const { cfg, db } = deps;
  const today = () => new Date().toISOString().slice(0, 10);

  const historyBlock = history.length > 0
    ? `\n\nПредыдущие сообщения (для контекста):\n${history
      .map((t) => `${t.role === 'user' ? 'Человек' : 'Ты'}: ${t.text}`)
      .join('\n')}`
    : '';

  const prompt = `${buildContext(db, cfg, today())}${historyBlock}\n\nСообщение: ${message}`;

  // Берём текст ПОСЛЕДНЕГО ответа модели, а не склейку всех.
  // Промежуточные сообщения — это преамбулы перед вызовами инструментов
  // («сейчас посмотрю», «исправляю»), и человеку они не нужны.
  let lastText = '';
  for await (const msg of query({
    prompt,
    options: {
      systemPrompt: SYSTEM_PROMPT,
      mcpServers: { finance: buildTools(db, today) },
      allowedTools: TOOL_NAMES,
      maxTurns: 15,
    },
  })) {
    if (msg.type === 'assistant') {
      const parts: string[] = [];
      for (const block of msg.message.content) {
        if (block.type === 'text') parts.push(block.text);
      }
      const text = parts.join('\n').trim();
      if (text) lastText = text;
    }
  }

  return lastText || 'Не понял. Переформулируй?';
}
