#!/usr/bin/env bash
#
# Единственная команда, которую разрешено запускать ключу с телефона.
#
# Прописана в authorized_keys через command="...", поэтому что бы ни
# прислал клиент, выполнится только это: аргументы клиента лежат
# в SSH_ORIGINAL_COMMAND и намеренно игнорируются.
#
# Входим отдельным пользователем finpay, а не служебным finbot: у finbot
# нет и не должно быть входа по SSH, иначе взлом самого бота дал бы
# возможность прописать себе постоянный доступ на сервер.
#
set -euo pipefail

# timeout — чтобы зависший клиент не держал соединение вечно.
exec /usr/bin/timeout 60 /usr/bin/sudo -n -u finbot /usr/local/sbin/finbot-applepay-run
